const DICT = {cs, en};
const PR = {cs: new Intl.PluralRules('cs'), en: new Intl.PluralRules('en')};
const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

// Jazyk z profilu nebo požadavku: jen podporované, jinak cs
function normLang(l) { return l === 'en' ? 'en' : 'cs'; }

// Text v jazyce L; vars.g === 'f' vybere ženský tvar, vars.n plurál; chybějící klíč spadne na češtinu
function tS(L, key, vars = {}) {
  const d = DICT[L] || cs;
  const pick = (o) => (vars.g === 'f' && has(o, key + '#f')) ? o[key + '#f'] : (has(o, key) ? o[key] : undefined);
  let v = pick(d);
  let lang = L;
  if (v === undefined) { v = pick(cs); lang = 'cs'; }
  if (v === undefined) return key;
  if (v && typeof v === 'object') {
    const f = PR[lang].select(Number(vars.n) || 0);
    v = has(v, f) ? v[f] : v.other; // cs „many“ (desetinná čísla) → other
  }
  return String(v).replace(/\{(\w+)\}/g, (m, k) => (has(vars, k) && vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ''));
}

module.exports = {tS, normLang, DICT};
